  /** 获取所有类型名称 */
  function getTypeNames() {
    return Object.keys(TRC_TYPES);
  }

  /** 获取单个类型完整数据 */
  function getType(typeName) {
    return TRC_TYPES[typeName] || null;
  }

  /** 根据关键词模糊匹配类型名 */
  function findTypeByKeyword(keyword) {
    if (!keyword) return null;
    const keys = Object.keys(TRC_TYPES);
    return keys.find(k => k.includes(keyword) || keyword.includes(k)) || null;
  }

  /**
   * 生成供 AI 提示词使用的精简类型参考（每类型约3行）
   * 避免 token 过多
   */
  function buildTypeReferenceForPrompt() {
    return Object.entries(TRC_TYPES).map(([name, d]) => {
      const 误解简 = d.常见误解.split('——')[0];
      const 误解释 = d.常见误解.split('——')[1] || '';
      const 发展简 = d.发展关键_文本.split('；')[0];
      return `【${name}】${d.核心天赋} 典型表现：${d.典型行为[0]}。常被误解为${误解简}——${误解释}。发展关键：${发展简}。`;
    }).join('\n\n');
  }

